// Generates the phone country picker's data from installed packages. Run after upgrading either:
//   node scripts/generate-countries.mjs
// - src/lib/countries.ts: every country libphonenumber-js knows, with its English name and calling
//   code, sorted by name. `main` marks the main country for a shared code (+44 is the UK, +1 the US),
//   so searching by code lists it first. A smoke test fails if this list and the library ever disagree.
// - public/flags/<CODE>.svg: each country's flag from country-flag-icons (MIT, licence copied alongside).
import { copyFileSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { getCountries, getCountryCallingCode } from "libphonenumber-js/min";
import metadata from "libphonenumber-js/min/metadata";

const names = new Intl.DisplayNames(["en"], { type: "region" });
const countries = getCountries()
  .map((code) => {
    const dial = getCountryCallingCode(code);
    return { code, name: names.of(code) ?? code, dial, main: metadata.country_calling_codes[dial][0] === code };
  })
  .sort((a, b) => a.name.localeCompare(b.name, "en"));

const rows = countries
  .map((c) => `  { code: "${c.code}", name: ${JSON.stringify(c.name)}, dial: "${c.dial}"${c.main ? ", main: true" : ""} },`)
  .join("\n");

writeFileSync(
  new URL("../src/lib/countries.ts", import.meta.url),
  `// Generated by scripts/generate-countries.mjs from libphonenumber-js. Do not edit by hand.
import type { CountryCode } from "libphonenumber-js/min";

/** main: the main country for its calling code, e.g. the UK for +44 (shared with Guernsey, Jersey, Isle of Man). */
export type Country = { code: CountryCode; name: string; dial: string; main?: boolean };

export const COUNTRIES: Country[] = [
${rows}
];
`,
);
console.log(`Wrote ${countries.length} countries to src/lib/countries.ts`);

const flagsPackage = dirname(createRequire(import.meta.url).resolve("country-flag-icons/package.json"));
const flagsDir = new URL("../public/flags/", import.meta.url);
rmSync(flagsDir, { recursive: true, force: true });
mkdirSync(flagsDir, { recursive: true });
for (const { code } of countries) {
  copyFileSync(join(flagsPackage, "3x2", `${code}.svg`), new URL(`${code}.svg`, flagsDir));
}
copyFileSync(join(flagsPackage, "LICENSE"), new URL("LICENSE.txt", flagsDir));
console.log(`Copied ${countries.length} flags to public/flags/`);
