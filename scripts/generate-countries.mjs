// Generates src/lib/countries.ts: every country libphonenumber-js knows, with its English name and
// calling code, sorted by name. Run after upgrading libphonenumber-js:
//   node scripts/generate-countries.mjs
// A smoke test fails if the generated list and the installed library ever disagree.
import { writeFileSync } from "node:fs";
import { getCountries, getCountryCallingCode } from "libphonenumber-js/min";

const names = new Intl.DisplayNames(["en"], { type: "region" });
const countries = getCountries()
  .map((code) => ({ code, name: names.of(code) ?? code, dial: getCountryCallingCode(code) }))
  .sort((a, b) => a.name.localeCompare(b.name, "en"));

const rows = countries.map((c) => `  { code: "${c.code}", name: ${JSON.stringify(c.name)}, dial: "${c.dial}" },`).join("\n");

writeFileSync(
  new URL("../src/lib/countries.ts", import.meta.url),
  `// Generated by scripts/generate-countries.mjs from libphonenumber-js. Do not edit by hand.
import type { CountryCode } from "libphonenumber-js/min";

export type Country = { code: CountryCode; name: string; dial: string };

export const COUNTRIES: Country[] = [
${rows}
];
`,
);
console.log(`Wrote ${countries.length} countries to src/lib/countries.ts`);
